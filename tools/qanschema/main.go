// qanschema replays the ClickHouse migrations of PMM (qan-api2/migrations/sql)
// and writes internal/inspect/qan_columns.txt: the column order and types of
// pmm.metrics after each PMM release that changed it. Run it through
// tools/update-qan-schema.sh, which fetches the migrations and their release
// tags.
//
// Any statement on the metrics table it does not understand is an error, so
// a new kind of migration is noticed instead of producing a wrong layout.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"pmm-dump-inspect/internal/qantype"
)

type column struct{ name, typ string }

func main() {
	dir := flag.String("sql", "", "directory with the *.up.sql migrations")
	versions := flag.String("versions", "", `file with "<migration file> <first PMM release or unreleased>" lines`)
	release := flag.String("release", "", "latest PMM release tag")
	source := flag.String("source", "", "where the migrations come from (repo@commit)")
	checked := flag.String("checked", "", "date of this run (YYYY-MM-DD)")
	flag.Parse()
	if *dir == "" || *versions == "" || *release == "" {
		flag.Usage()
		os.Exit(2)
	}
	tags, err := readVersions(*versions)
	if err != nil {
		fail(err)
	}
	files, err := filepath.Glob(filepath.Join(*dir, "*.up.sql"))
	if err != nil {
		fail(err)
	}
	sort.Strings(files)
	if len(files) == 0 {
		fail(fmt.Errorf("no *.up.sql in %s", *dir))
	}

	w := bufio.NewWriter(os.Stdout)
	fmt.Fprintf(w, "# pmm.metrics column order (\"SELECT * FROM metrics\") after each PMM release\n")
	fmt.Fprintf(w, "# that changed it. Generated by tools/update-qan-schema.sh, do not edit.\n")
	fmt.Fprintf(w, "# source: %s\n", *source)
	fmt.Fprintf(w, "# latest-release: %s\n", strings.TrimPrefix(*release, "v"))
	fmt.Fprintf(w, "# checked: %s\n", *checked)

	var cols, last []column
	for i, f := range files {
		base := filepath.Base(f)
		tag, ok := tags[base]
		if !ok {
			fail(fmt.Errorf("%s: no release in %s", base, *versions))
		}
		b, err := os.ReadFile(f)
		if err != nil {
			fail(err)
		}
		if cols, err = apply(cols, string(b)); err != nil {
			fail(fmt.Errorf("%s: %w", base, err))
		}
		// one block per release: emit after its last migration
		if i+1 < len(files) && tags[filepath.Base(files[i+1])] == tag {
			continue
		}
		if same(cols, last) {
			continue
		}
		fmt.Fprintf(w, "\n@schema since=%s migrations=%s columns=%d\n", tag, strings.SplitN(base, "_", 2)[0], len(cols))
		for _, c := range cols {
			if !valid(c.typ) {
				fail(fmt.Errorf("%s: column %s has type %s, which internal/inspect/qanschema.go cannot check yet", base, c.name, c.typ))
			}
			fmt.Fprintf(w, "%s %s\n", c.name, c.typ)
		}
		last = append([]column(nil), cols...)
	}
	if err := w.Flush(); err != nil {
		fail(err)
	}
}

func valid(t string) bool {
	_, ok := qantype.Check(t)
	return ok
}

func readVersions(path string) (map[string]string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, l := range strings.Split(string(b), "\n") {
		if f := strings.Fields(l); len(f) == 2 {
			out[f[0]] = strings.TrimPrefix(f[1], "v")
		}
	}
	return out, nil
}

func same(a, b []column) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

