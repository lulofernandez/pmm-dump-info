var (
	lineComment = regexp.MustCompile(`--[^\n]*`)
	template    = regexp.MustCompile(`\{\{[^}]*\}\}`)
	space       = regexp.MustCompile(`\s+`)
)

// apply runs the statements of one migration file on the column list.
func apply(cols []column, sql string) ([]column, error) {
	sql = template.ReplaceAllString(stripComments(sql), "X")
	for _, st := range splitTop(sql, ';') {
		st = strings.TrimSpace(st)
		if st == "" {
			continue
		}
		up := strings.ToUpper(st)
		var err error
		switch {
		case strings.HasPrefix(up, "CREATE TABLE"):
			if table(st[len("CREATE TABLE"):]) != "metrics" {
				continue
			}
			cols, err = create(st)
		case strings.HasPrefix(up, "ALTER TABLE"):
			rest := strings.TrimSpace(st[len("ALTER TABLE"):])
			if table(rest) != "metrics" {
				continue
			}
			rest = strings.TrimSpace(rest[len(firstWord(rest)):])
			if strings.HasPrefix(strings.ToUpper(rest), "ON CLUSTER") {
				rest = strings.TrimSpace(rest[len("ON CLUSTER"):])
				rest = strings.TrimSpace(rest[len(firstWord(rest)):])
			}
			for _, a := range splitTop(rest, ',') {
				if cols, err = alter(cols, strings.TrimSpace(a)); err != nil {
					break
				}
			}
		default:
			if regexp.MustCompile(`(?i)\bmetrics\b`).MatchString(st) {
				err = fmt.Errorf("statement on metrics not understood: %.80s", st)
			}
		}
		if err != nil {
			return nil, err
		}
	}
	return cols, nil
}

// stripComments removes "-- ..." outside quotes.
func stripComments(s string) string {
	var b strings.Builder
	q := byte(0)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case q != 0:
			if c == '\\' && i+1 < len(s) {
				b.WriteByte(c)
				i++
				c = s[i]
			} else if c == q {
				q = 0
			}
		case c == '\'' || c == '`' || c == '"':
			q = c
		case c == '-' && i+1 < len(s) && s[i+1] == '-':
			j := strings.IndexByte(s[i:], '\n')
			if j < 0 {
				return b.String()
			}
			i += j - 1
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

// splitTop splits on sep outside quotes and parentheses.
func splitTop(s string, sep byte) []string {
	var out []string
	depth, q, start := 0, byte(0), 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case q != 0:
			if c == '\\' {
				i++
			} else if c == q {
				q = 0
			}
		case c == '\'' || c == '`' || c == '"':
			q = c
		case c == '(':
			depth++
		case c == ')':
			depth--
		case c == sep && depth == 0:
			out = append(out, s[start:i])
			start = i + 1
		}
	}
	return append(out, s[start:])
}

func firstWord(s string) string {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "`") {
		if j := strings.IndexByte(s[1:], '`'); j >= 0 {
			return s[:j+2]
		}
	}
	if j := strings.IndexAny(s, " \t\n("); j >= 0 {
		return s[:j]
	}
	return s
}

// ident unquotes a name; "pmm.metrics" is the metrics table.
func ident(s string) string { return strings.TrimPrefix(strings.Trim(s, "`\""), "pmm.") }

// table is the table name at the start of s, after IF [NOT] EXISTS.
func table(s string) string {
	s = strings.TrimSpace(s)
	for _, p := range []string{"IF NOT EXISTS", "IF EXISTS"} {
		if strings.HasPrefix(strings.ToUpper(s), p) {
			s = strings.TrimSpace(s[len(p):])
		}
	}
	return ident(firstWord(s))
}

func create(st string) ([]column, error) {
	open := strings.IndexByte(st, '(')
	if open < 0 {
		return nil, fmt.Errorf("CREATE TABLE metrics without columns")
	}
	depth, end := 0, -1
	for i := open; i < len(st) && end < 0; i++ {
		switch st[i] {
		case '(':
			depth++
		case ')':
			if depth--; depth == 0 {
				end = i
			}
		}
	}
	if end < 0 {
		return nil, fmt.Errorf("CREATE TABLE metrics: unbalanced parentheses")
	}
	var cols []column
	for _, item := range splitTop(st[open+1:end], ',') {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		switch strings.ToUpper(firstWord(item)) {
		case "INDEX", "PROJECTION", "CONSTRAINT":
			continue
		}
		c, pos, err := columnDef(item)
		if err != nil {
			return nil, err
		}
		if pos != "" {
			return nil, fmt.Errorf("position %q in CREATE TABLE", pos)
		}
		if c != nil {
			cols = append(cols, *c)
		}
	}
	return cols, nil
}

// clause keywords that end a column type.
var stops = []string{"COMMENT", "DEFAULT", "MATERIALIZED", "ALIAS", "EPHEMERAL", "CODEC", "TTL", "AFTER", "FIRST", "SETTINGS", "NOT", "NULL"}

// columnDef parses "name Type [DEFAULT ..] [COMMENT '..'] [AFTER x | FIRST]".
// It returns nil for columns SELECT * does not return (MATERIALIZED, ALIAS,
// EPHEMERAL) and the position clause ("AFTER x", "FIRST" or "").
func columnDef(s string) (*column, string, error) {
	name := firstWord(s)
	rest := strings.TrimSpace(s[len(name):])
	depth, q, end := 0, byte(0), len(rest)
scan:
	for i := 0; i < len(rest); i++ {
		c := rest[i]
		switch {
		case q != 0:
			if c == '\\' {
				i++
			} else if c == q {
				q = 0
			}
		case c == '\'' || c == '`':
			q = c
		case c == '(':
			depth++
		case c == ')':
			depth--
		case depth == 0 && (c == ' ' || c == '\t' || c == '\n'):
			w := strings.ToUpper(firstWord(rest[i:]))
			for _, k := range stops {
				if w == k {
					end = i
					break scan
				}
			}
		}
	}
	typ := normType(rest[:end])
	if typ == "" {
		return nil, "", fmt.Errorf("column %s without type", name)
	}
	tail := strings.ToUpper(rest[end:])
	if regexp.MustCompile(`^\s*(MATERIALIZED|ALIAS|EPHEMERAL)\b`).MatchString(tail) {
		return nil, "", nil
	}
	pos := ""
	if m := regexp.MustCompile("(?i)\\b(AFTER\\s+`?[\\w.]+`?|FIRST)\\s*$").FindString(rest[end:]); m != "" {
		pos = strings.TrimSpace(m)
	}
	return &column{ident(name), typ}, pos, nil
}

// normType drops the spaces outside quotes: Enum8('a' = 1, 'b' = 2) -> Enum8('a'=1,'b'=2).
func normType(t string) string {
	var b strings.Builder
	q := byte(0)
	for i := 0; i < len(t); i++ {
		c := t[i]
		if q != 0 {
			if c == '\\' && i+1 < len(t) {
				b.WriteByte(c)
				i++
				c = t[i]
			} else if c == q {
				q = 0
			}
			b.WriteByte(c)
			continue
		}
		if c == '\'' {
			q = c
		}
		if c != ' ' && c != '\t' && c != '\n' && c != '\r' {
			b.WriteByte(c)
		}
	}
	return b.String()
}

func find(cols []column, name string) int {
	for i, c := range cols {
		if c.name == name {
			return i
		}
	}
	return -1
}

// alter applies one ALTER TABLE metrics action.
func alter(cols []column, a string) ([]column, error) {
	up := strings.ToUpper(space.ReplaceAllString(a, " "))
	trimIf := func(s string) string {
		for _, p := range []string{"IF NOT EXISTS ", "IF EXISTS "} {
			if strings.HasPrefix(strings.ToUpper(s), p) {
				return strings.TrimSpace(s[len(p):])
			}
		}
		return s
	}
	after := func(kw string) string { return trimIf(strings.TrimSpace(space.ReplaceAllString(a, " ")[len(kw):])) }
	switch {
	case strings.HasPrefix(up, "ADD COLUMN "):
		def := after("ADD COLUMN ")
		ifNot := strings.HasPrefix(up, "ADD COLUMN IF NOT EXISTS ")
		c, pos, err := columnDef(def)
		if err != nil || c == nil {
			return cols, err
		}
		if find(cols, c.name) >= 0 {
			if ifNot {
				return cols, nil
			}
			return nil, fmt.Errorf("ADD COLUMN %s: already exists", c.name)
		}
		at := len(cols)
		switch {
		case strings.EqualFold(pos, "FIRST"):
			at = 0
		case pos != "":
			ref := ident(strings.TrimSpace(pos[len("AFTER"):]))
			if at = find(cols, ref); at < 0 {
				return nil, fmt.Errorf("ADD COLUMN %s AFTER %s: no such column", c.name, ref)
			}
			at++
		}
		cols = append(cols[:at], append([]column{*c}, cols[at:]...)...)
	case strings.HasPrefix(up, "DROP COLUMN "):
		name := ident(firstWord(after("DROP COLUMN ")))
		i := find(cols, name)
		if i < 0 {
			if strings.HasPrefix(up, "DROP COLUMN IF EXISTS ") {
				return cols, nil
			}
			return nil, fmt.Errorf("DROP COLUMN %s: no such column", name)
		}
		cols = append(cols[:i], cols[i+1:]...)
	case strings.HasPrefix(up, "RENAME COLUMN "):
		f := strings.Fields(after("RENAME COLUMN "))
		if len(f) != 3 || !strings.EqualFold(f[1], "TO") {
			return nil, fmt.Errorf("RENAME COLUMN not understood: %s", a)
		}
		i := find(cols, ident(f[0]))
		if i < 0 {
			return nil, fmt.Errorf("RENAME COLUMN %s: no such column", f[0])
		}
		cols[i].name = ident(f[2])
	case strings.HasPrefix(up, "MODIFY COLUMN "):
		def := after("MODIFY COLUMN ")
		name := ident(firstWord(def))
		i := find(cols, name)
		if i < 0 {
			return nil, fmt.Errorf("MODIFY COLUMN %s: no such column", name)
		}
		rest := strings.ToUpper(strings.TrimSpace(def[len(firstWord(def)):]))
		if strings.HasPrefix(rest, "COMMENT") || strings.HasPrefix(rest, "REMOVE") || strings.HasPrefix(rest, "DEFAULT") || strings.HasPrefix(rest, "CODEC") || strings.HasPrefix(rest, "TTL") {
			return cols, nil // no type change
		}
		c, pos, err := columnDef(def)
		if err != nil {
			return nil, err
		}
		if c == nil || pos != "" {
			return nil, fmt.Errorf("MODIFY COLUMN %s: moving or materializing a column is not supported", name)
		}
		cols[i].typ = c.typ
	case strings.HasPrefix(up, "COMMENT COLUMN "), strings.HasPrefix(up, "ADD INDEX "), strings.HasPrefix(up, "DROP INDEX "),
		strings.HasPrefix(up, "MATERIALIZE INDEX "), strings.HasPrefix(up, "MODIFY TTL "), strings.HasPrefix(up, "MODIFY SETTING "),
		strings.HasPrefix(up, "MODIFY ORDER BY "), strings.HasPrefix(up, "ADD PROJECTION "), strings.HasPrefix(up, "DROP PROJECTION "):
		// no effect on SELECT * columns
	default:
		return nil, fmt.Errorf("ALTER TABLE metrics action not understood: %.80s", a)
	}
	return cols, nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "qanschema:", err)
	os.Exit(1)
}
